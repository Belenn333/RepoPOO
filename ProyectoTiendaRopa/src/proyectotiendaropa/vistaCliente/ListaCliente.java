    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // Obtiene los datos ingresados
        String codigo = txtCodigo.getText().trim();
        String nombre = txtNombre.getText().trim();
        String dni = txtDni.getText().trim();

// Obtiene el modelo de la tabla
        DefaultTableModel modelo
                = (DefaultTableModel) tbCliente.getModel();

// Limpia los resultados anteriores
        modelo.setRowCount(0);

        boolean encontrado = false;

// BUSCAR POR CODIGO
        if (!codigo.isEmpty()) {

            for (Cliente c : Principal.listaClientes) {

                // Utiliza la sobrecarga buscar(String codigo)
                c.buscar(codigo);

                // Comprueba si el codigo coincide
                if (c.getCodigo() != null
                        && c.getCodigo().equalsIgnoreCase(codigo)) {

                    modelo.addRow(new Object[]{
                        c.getCodigo(),
                        c.getNombre(),
                        c.getDni(),
                        c.getTelefono()
                    });

                    encontrado = true;
                }
            }

// BUSCAR POR NOMBRE Y DNI
        } else if (!nombre.isEmpty() && !dni.isEmpty()) {

            for (Cliente c : Principal.listaClientes) {

                // Utiliza la sobrecarga buscar(String nombre, String dni)
                c.buscar(nombre, dni);

                // Comprueba si coinciden el nombre y el DNI
                if (c.getNombre() != null
                        && c.getNombre().equalsIgnoreCase(nombre)
                        && c.getDni() != null
                        && c.getDni().equals(dni)) {

                    modelo.addRow(new Object[]{
                        c.getCodigo(),
                        c.getNombre(),
                        c.getDni(),
                        c.getTelefono()
                    });

                    encontrado = true;
                }
            }

        } else {
            JOptionPane.showMessageDialog(
                    this,
                    "Ingrese un codigo o un nombre y DNI para buscar."
            );
            return;
        }

// Informa si no se encontro ningun cliente
        if (!encontrado) {
            JOptionPane.showMessageDialog(
                    this,
                    "Cliente no encontrado."
            );
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

