    // Carga los clientes registrados en la tabla
    private void cargarClientes() {

        // Obtiene el modelo de la tabla
        DefaultTableModel modelo
                = (DefaultTableModel) tbCliente.getModel();

        // Limpia las filas existentes
        modelo.setRowCount(0);

        // Recorre la lista de clientes compartida
        for (Cliente c : Principal.listaClientes) {

            // Agrega cada cliente como una fila en la tabla
            modelo.addRow(new Object[]{
                c.getCodigo(),
                c.getNombre(),
                c.getDni(),
                c.getTelefono()
            });
        }
    }
