    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        // TODO add your handling code here:
        // Obtiene los datos ingresados en los JTextField
        String codigo = txtCodigo.getText();
        String nombre = txtNombre.getText();
        String talla = txtTalla.getText();
        String categoria = txtCategoria.getText();
        String color = txtColor.getText();

        double precio = Double.parseDouble(
                txtPrecio.getText());

        int stock = Integer.parseInt(
                txtStock.getText());

        // Verifica si el código ya existe
        boolean existe = false;

        for(Ropa r : Principal.listaRopa){

            if(r.getCodigo().equalsIgnoreCase(codigo)){

                existe = true;
                break;
            }
        }

        // Registra la prenda si el código no existe
        if(!existe){

            Ropa ropa = new Ropa();

            ropa.agregar(
                    codigo,
                    nombre,
                    talla,
                    categoria,
                    color,
                    precio,
                    stock);

            Principal.listaRopa.add(ropa);
            
            Principal.guardarTodasLasPrendas();

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Prenda registrada correctamente");

            //Limpia los campos
            txtCodigo.setText("");
            txtNombre.setText("");
            txtTalla.setText("");
            txtCategoria.setText("");
            txtColor.setText("");
            txtPrecio.setText("");
            txtStock.setText("");

        }
        else{

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Error: el codigo ya existe");
        }
        
    }//GEN-LAST:event_btnRegistrarActionPerformed

