    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
        String codigo = txtCodigo.getText().trim();
        String dni = txtDNI.getText().trim();

        DefaultTableModel modelo =
                (DefaultTableModel) tblVentas.getModel();

        modelo.setRowCount(0);

        boolean encontrada = false;

        for(Venta v : Principal.listaVentas){

            if((!codigo.isEmpty() && v.buscar(codigo))
                    ||
               (!dni.isEmpty() && v.buscar(dni, true))){

                modelo.addRow(
                        v.mostrar(true)
                );

                encontrada = true;
            }
        }

        if(!encontrada){

            JOptionPane.showMessageDialog(
                    this,
                    "Venta no encontrada.");
        }
    
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        String codigo = txtCodigo.getText().trim();

        if(codigo.isEmpty()){

            JOptionPane.showMessageDialog(
                    this,
                    "Ingrese el código de la venta.");

            return;
        }

        int opcion = JOptionPane.showConfirmDialog(
                this,
                "¿Está seguro de eliminar la venta?",
                "Confirmar eliminación",
                JOptionPane.YES_NO_OPTION);

        if(opcion == JOptionPane.YES_OPTION){

            boolean eliminada = false;

            for(int i = 0;
                    i < Principal.listaVentas.size();
                    i++){

                if(Principal.listaVentas.get(i)
                        .eliminar(codigo)){

                    Principal.listaVentas.remove(i);

                    Principal.guardarTodasLasVentas();

                    eliminada = true;

                    JOptionPane.showMessageDialog(
                            this,
                            "Venta eliminada correctamente.");

                    break;
                }
            }

            if(!eliminada){

                JOptionPane.showMessageDialog(
                        this,
                        "Venta no encontrada.");
            }

            // Limpiar campos
            txtCodigo.setText("");
            txtDNI.setText("");

            // Actualizar tabla
            cargarVentasTabla();
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

