    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
        String codigo = txtCodigo.getText();

        boolean encontrada = false;

        for(Ropa r : Principal.listaRopa){

            if(r.getCodigo().equalsIgnoreCase(codigo)){

                txtNombre.setText(r.getNombre());
                txtTalla.setText(r.getTalla());
                txtCategoria.setText(r.getCategoria());
                txtColor.setText(r.getColor());
                txtPrecio.setText(String.valueOf(r.getPrecio()));

                encontrada = true;
                break;
            }
        }

        if(!encontrada){
            JOptionPane.showMessageDialog(
                    this,
                    "Prenda no encontrada");
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        // TODO add your handling code here:
        String codigo = txtCodigo.getText();

        boolean modificada = false;
        
        //Recorre la lista de prendas
        for(Ropa r : Principal.listaRopa){

            if(r.getCodigo().equalsIgnoreCase(codigo)){

            if(r.agregar(
                    txtNombre.getText(),
                    txtTalla.getText(),
                    txtCategoria.getText(),
                    txtColor.getText(),
                    Double.parseDouble(txtPrecio.getText()))){

                modificada = true;

                Principal.guardarTodasLasPrendas();

                JOptionPane.showMessageDialog( this, "Prenda modificada correctamente");
            }

            break;
            }
        }

        if(!modificada){

            JOptionPane.showMessageDialog(
                    this,
                    "Prenda no encontrada");
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

