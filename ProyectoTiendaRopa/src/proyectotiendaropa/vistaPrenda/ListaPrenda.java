    private void cargarPrendas(){

        DefaultTableModel modelo =
                (DefaultTableModel) tbPrenda.getModel();

        // Limpia la tabla
        modelo.setRowCount(0);

        // Recorre la lista de prendas
        for(Ropa r : Principal.listaRopa){

            modelo.addRow(new Object[]{
                r.getCodigo(),
                r.getNombre(),
                r.getTalla(),
                r.getCategoria(),
                r.getColor(),
                r.getPrecio(),
                r.getStock()
            });
        }
    }


